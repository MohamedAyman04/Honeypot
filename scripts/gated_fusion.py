            "high precision in the stored run. The process-domain cannot add material TPs",
            "in the cases where this high-precision network detector is silent, because",
            "those 'silent' attacks are the physically stealthy attacks (Phase 5, 7) that",
            "also produce small process-feature anomalies below the detection threshold.",
            "",
            "**For the paper.** This is an honest finding: state that (1) network-only",
            "achieves the highest F1 driven by the Modbus semantic layer's near-perfect",
