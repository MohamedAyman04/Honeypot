# ── Entry point ────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Gated/hierarchical fusion — network-primary, process-gated")
    parser.add_argument("--ds1", default="results/20260724_014825")
    parser.add_argument("--ds2", default="results/20260725_055634")
    parser.add_argument("--out", default="results/full_architecture_realistic_v2")
    parser.add_argument(
        "--baseline-csv",
        default="results/full_architecture_realistic_v2/network_vs_process_vs_combined.csv",
        help="Path to the stored baseline CSV",
    )
    args = parser.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # Load stored baselines
    baseline_csv = pd.read_csv(args.baseline_csv)
    print(f"Loaded {len(baseline_csv)} baseline rows from {args.baseline_csv}")

    # ── Dataset 1 (frac=0.60, v2 split) ───────────────────────────────────────
    set_seed()
    df1_new, meta1 = evaluate_dataset_gated_only(args.ds1, frac=DS1_FRAC)
    df1_new.to_csv(out / "gated_fusion_d1.csv", index=False)
    print(f"\nDataset 1 (gated only) → {out / 'gated_fusion_d1.csv'}")

    # ── Dataset 2 (frac=0.45, v4 split) ───────────────────────────────────────
    set_seed()
    df2_new, meta2 = evaluate_dataset_gated_only(args.ds2, frac=DS2_FRAC)
    df2_new.to_csv(out / "gated_fusion_d2.csv", index=False)
    print(f"\nDataset 2 (gated only) → {out / 'gated_fusion_d2.csv'}")

    # ── Consolidated CSV (baselines + new strategies) ─────────────────────────
    # Reformat baselines to match new format
    b_cols_map = {
        "configuration": "configuration", "dataset": "dataset",
        "precision": "Precision", "recall": "Recall", "f1": "F1",
        "tp": "TP", "fp": "FP", "tn": "TN", "fn": "FN",
    }
    b_clean = baseline_csv.rename(columns=b_cols_map)[[
        "configuration", "Precision", "Recall", "F1",
        "TP", "FP", "TN", "FN", "dataset",
    ]]
    # Normalise dataset labels
    b_clean["dataset"] = b_clean["dataset"].str.extract(r"(\d{8}_\d{6})")
    combined = pd.concat([b_clean, df1_new, df2_new], ignore_index=True)
    combined.to_csv(out / "gated_fusion_comparison.csv", index=False)
    print(f"\nConsolidated → {out / 'gated_fusion_comparison.csv'}")

    # ── Report ─────────────────────────────────────────────────────────────────
    all_meta = {
        "dataset_1": {"data_dir": args.ds1, "val_frac": DS1_FRAC, "calibration": meta1},
        "dataset_2": {"data_dir": args.ds2, "val_frac": DS2_FRAC, "calibration": meta2},
        "gated_fpr_caps": GATED_FPR_CAPS,
        "nmg_mean_dev_candidates": NMG_MEAN_DEV_CANDIDATES,
        "seed": SEED,
        "baselines_source": args.baseline_csv,
    }
    write_report(
        out, baseline_csv, df1_new, df2_new, all_meta,
        ds1_label=Path(args.ds1).name,
        ds2_label=Path(args.ds2).name,
    )


if __name__ == "__main__":
    main()
