#!/usr/bin/env python3
"""Gated fusion evaluation — hierarchical network-primary, process-gated strategy.

Problem
-------
Naive OR / weighted-vote fusion degrades F1 vs network-only because process-domain
generates large false-positive volume faster than it adds unique true positives.

Solution — Gated Fusion
-----------------------
Network-domain (Layer 1 + ML) acts as the PRIMARY detector.
Process-domain is only CONSULTED where the network domain is silent — and only
when an elevated-confidence or mechanism-specific filter is satisfied.

Two new strategies:

1. Gated-Confidence (GC):
   alert = network_fires  OR  (proc_score >= gate_t  AND  NOT network_fires)
   gate_t: calibrated on network-silent validation rows, under conservative FPR caps.
   Three FPR caps: strict=0.5%, moderate=1.5%, relaxed=3.5%.

2. Narrow Mechanism Gate (NMG):
   alert = network_fires  OR  (|mean_dev|>t AND write_freq=0 AND NOT network_fires)
   Directly encodes Phase-8 "large deviation + no write" physical-inconsistency.
   Threshold t calibrated on network-silent validation rows via F1-maximisation.

Evaluation approach
-------------------
For the BASELINE configurations (network-only, process-only, OR fusion, weighted
vote), we read the EXISTING published results from network_vs_process_vs_combined.csv
(generated by the confirmed-correct scripts) to guarantee exact reproducibility.

For the NEW gated configurations, we run fresh calibration using the v2/v4 pipeline
layer vectors. The network-domain and process-domain binary predictions are derived
from existing calibrated layer outputs. The GATING adds process-domain alerts in
the network-silent region only.

Constraints
-----------
- SEED=42, validation-only calibration, no test-set peeking.
- D1 uses frac=0.60 (v2 split), D2 uses frac=0.45 (v4 split) to match published
  test set sizes.
- Baseline numbers are read from the stored CSV, not recomputed.

Outputs
-------
- results/full_architecture_realistic_v2/gated_fusion_comparison.csv
- results/full_architecture_realistic_v2/GATED_FUSION_REPORT.md
"""
